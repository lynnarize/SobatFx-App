const DICTS: Record<Lang, Record<Key, string>> = { en, id };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars) {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function parseLang(v: string | undefined | null): Lang {
  return v === "en" ? "en" : "id";
}

export const localeOf = (lang: Lang) => (lang === "id" ? "id-ID" : "en-US");

const NAME_ID: [RegExp, string][] = [
  [/US Dollar/g, "Dolar AS"],
  [/^Gold/, "Emas"],
  [/British Pound/g, "Pound Inggris"],
  [/Japanese Yen/g, "Yen Jepang"],
  [/Australian Dollar/g, "Dolar Australia"],
  [/Canadian Dollar/g, "Dolar Kanada"],
  [/Swiss Franc/g, "Franc Swiss"],
];

/** Instrument display name in the UI language. */
export function instrumentName(name: string, lang: Lang) {
  return lang === "id" ? NAME_ID.reduce((s, [re, r]) => s.replace(re, r), name) : name;
}

